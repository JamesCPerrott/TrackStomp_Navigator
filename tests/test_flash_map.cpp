#include "config.h"
#include "harness.h"

// Four regions: image, config, bonds, E10 reserve. Contiguous, sector-aligned,
// non-overlapping, and ending at the top of the 4 MB flash.
int main() {
    REQUIRE(FLASH_TOTAL_BYTES == (4U * 1024U * 1024U));
    REQUIRE(FLASH_SECTOR_BYTES == 4096U);

    REQUIRE(IMAGE_FLASH_LIMIT == 0x3FC000U);
    REQUIRE(CONFIG_FLASH_OFFSET == 0x3FC000U);
    REQUIRE(BOND_FLASH_OFFSET == 0x3FD000U);
    REQUIRE(BOND_FLASH_SIZE == (2U * FLASH_SECTOR_BYTES));
    REQUIRE(FLASH_E10_RESERVED_OFFSET == 0x3FF000U);

    REQUIRE(IMAGE_FLASH_LIMIT % FLASH_SECTOR_BYTES == 0U);
    REQUIRE(CONFIG_FLASH_OFFSET % FLASH_SECTOR_BYTES == 0U);
    REQUIRE(BOND_FLASH_OFFSET % FLASH_SECTOR_BYTES == 0U);
    REQUIRE(BOND_FLASH_SIZE % FLASH_SECTOR_BYTES == 0U);
    REQUIRE(FLASH_E10_RESERVED_OFFSET % FLASH_SECTOR_BYTES == 0U);

    REQUIRE(IMAGE_FLASH_LIMIT == CONFIG_FLASH_OFFSET);
    REQUIRE((CONFIG_FLASH_OFFSET + FLASH_SECTOR_BYTES) == BOND_FLASH_OFFSET);
    REQUIRE((BOND_FLASH_OFFSET + BOND_FLASH_SIZE) == FLASH_E10_RESERVED_OFFSET);
    REQUIRE((FLASH_E10_RESERVED_OFFSET + FLASH_SECTOR_BYTES) == FLASH_TOTAL_BYTES);

    REQUIRE(CONFIG_FLASH_OFFSET < BOND_FLASH_OFFSET);
    REQUIRE(BOND_FLASH_OFFSET < FLASH_E10_RESERVED_OFFSET);
    REQUIRE(FLASH_E10_RESERVED_OFFSET < FLASH_TOTAL_BYTES);

    return 0;
}
